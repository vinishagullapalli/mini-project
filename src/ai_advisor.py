"""
ai_advisor.py
Groq LLM-Powered AI Copilot for Retail Replenishment and Demand Analysis.
Provides actionable executive commentary, stockout risk mitigation strategies,
and natural language inventory diagnostics using Groq API.
Includes robust fallback for offline or unauthenticated scenarios.
"""

import os
from typing import Dict, Any, Optional
from dotenv import load_dotenv

load_dotenv()


class RetailAIAdvisor:
    """
    AI Copilot utilizing Groq's high-speed inference for intelligent retail replenishment decisions.
    """

    def __init__(self, api_key: Optional[str] = None, model: str = "openai/gpt-oss-120b"):
        self.api_key = api_key or os.getenv("GROQ_API_KEY", "")
        self.model = model
        self.client = None
        
        if self.api_key and self.api_key.strip():
            try:
                from groq import Groq
                self.client = Groq(api_key=self.api_key.strip())
            except Exception as e:
                print(f"Warning: Could not initialize Groq client: {e}")
                self.client = None

    def analyze_replenishment_plan(
        self,
        store_id: str,
        store_name: str,
        sku_id: str,
        sku_name: str,
        category: str,
        forecast_demand: float,
        current_on_hand: int,
        lead_time_days: int,
        safety_stock: int,
        reorder_point: int,
        recommended_order: int,
        order_cost: float,
        expected_margin: float,
        stockout_risk: bool,
        perishability_risk: bool
    ) -> str:
        """
        Generates an executive briefing explaining the replenishment recommendation.
        """
        context_prompt = f"""
You are an expert Retail Supply Chain & Inventory Optimization Director.
Analyze the following store replenishment recommendation generated by our Random Forest Time-Aware Model:

Store: {store_name} ({store_id})
SKU: {sku_name} [{sku_id}] | Category: {category}
Forecasted Next-Week Demand: {forecast_demand:.1f} units
Current Inventory On-Hand: {current_on_hand} units
Supplier Lead Time: {lead_time_days} days
Dynamic Safety Stock Buffer: {safety_stock} units
Reorder Point (ROP): {reorder_point} units
Recommended Purchase Order: {recommended_order} units
Order Total Cost: ${order_cost:,.2f} | Expected Margin: ${expected_margin:,.2f}
Imminent Stockout Risk: {'YES (URGENT)' if stockout_risk else 'No'}
Perishability / Spoilage Alert: {'YES (Caution)' if perishability_risk else 'No'}

Please provide a concise, directly actionable 3-point briefing:
1. Executive Rationale: Why this order size is optimal balancing stockout risk vs holding cost.
2. Immediate Action Item: Instructions for store replenishment / procurement team.
3. Risk Mitigation: Specific steps to manage lead time, perishability, or supplier fulfillment.
Keep tone professional, analytical, and crisp.
"""
        if self.client:
            try:
                response = self.client.chat.completions.create(
                    model=self.model,
                    messages=[
                        {"role": "system", "content": "You are a senior retail demand forecasting and inventory analytics advisor."},
                        {"role": "user", "content": context_prompt}
                    ],
                    temperature=0.2,
                    max_tokens=450
                )
                return response.choices[0].message.content.strip()
            except Exception as e:
                print(f"Groq API call encountered an error: {e}. Falling back to deterministic advisor.")

        # High quality deterministic rule-based analysis (fallback if API offline)
        status = "CRITICAL ACTION REQUIRED" if stockout_risk else ("ORDER RECOMMENDED" if recommended_order > 0 else "STOCK BALANCED")
        briefing = f"""### 📋 Executive Replenishment Briefing [{status}]
- **Demand Context**: Expected coming week demand is **{forecast_demand:.1f} units**. Current on-hand is **{current_on_hand} units**, against a calculated Reorder Point (ROP) of **{reorder_point} units**.
- **Procurement Order**: Recommend placing a purchase order for **{recommended_order} units** (${order_cost:,.2f} capital commitment). Safety stock is budgeted at **{safety_stock} units** to cover {lead_time_days}-day supplier lead time variance at 95% service level.
- **Risk Assessment**: {"🚨 **Urgent Stockout Risk**: On-hand inventory is insufficient to cover lead time demand. Fast-track order with priority freight." if stockout_risk else "✅ Inventory levels are within safe operating thresholds."}
{"⚠️ **Perishability Warning**: This SKU has a short shelf-life. Avoid bulk buffering to prevent shrinkage." if perishability_risk else ""}
"""
        return briefing

    def generate_store_summary(self, plan_summary_stats: Dict[str, Any]) -> str:
        """
        Summarizes entire store replenishment run.
        """
        prompt = f"""
Summarize the weekly store replenishment plan metrics for retail store leadership:
- Total SKUs Evaluated: {plan_summary_stats.get('total_skus', 0)}
- SKUs Requiring Reorder: {plan_summary_stats.get('reorder_count', 0)}
- Total Capital Commitment: ${plan_summary_stats.get('total_order_cost', 0.0):,.2f}
- Projected Margin: ${plan_summary_stats.get('total_expected_margin', 0.0):,.2f}
- Urgent Stockout Alerts: {plan_summary_stats.get('stockout_alerts', 0)}
- Perishability Alerts: {plan_summary_stats.get('perishability_alerts', 0)}

Provide 3 bullet points highlighting priority procurement actions and working capital efficiency.
"""
        if self.client:
            try:
                response = self.client.chat.completions.create(
                    model=self.model,
                    messages=[
                        {"role": "system", "content": "You are a Retail Operations and Procurement Director."},
                        {"role": "user", "content": prompt}
                    ],
                    temperature=0.2,
                    max_tokens=300
                )
                return response.choices[0].message.content.strip()
            except Exception as e:
                print(f"Groq API call error: {e}")

        return f"""- **Order Execution**: Out of {plan_summary_stats.get('total_skus', 0)} SKUs, **{plan_summary_stats.get('reorder_count', 0)} SKUs** breached reorder thresholds requiring an immediate total PO of **${plan_summary_stats.get('total_order_cost', 0.0):,.2f}**.
- **Revenue Protection**: Timely replenishment protects **${plan_summary_stats.get('total_expected_margin', 0.0):,.2f}** in projected retail gross profit.
- **Operational Priorities**: Prioritize expedited delivery for **{plan_summary_stats.get('stockout_alerts', 0)} items** at imminent stockout risk, while closely monitoring rotation on **{plan_summary_stats.get('perishability_alerts', 0)} perishable SKUs**.
"""
